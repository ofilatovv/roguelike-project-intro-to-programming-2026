/* combat.h — правила бою гравця з ворогом. */
#ifndef COMBAT_H
#define COMBAT_H
#include "types.h"

/*
 * Гравець б'є ворога. `roll` — число 0..99 (передається ззовні, щоб бій
 * можна було детерміновано тестувати).
 *  - ворог завжди втрачає 1 HP;
 *  - якщо ворог вижив і roll < 70, він б'є у відповідь (-1 HP гравцю);
 *  - убитий ворог відповіді не дає.
 * Повертає, скільки HP втратив гравець (0 або 1).
 */
int combat_player_attack(Entity *player, Entity *enemy, int roll);

#endif
